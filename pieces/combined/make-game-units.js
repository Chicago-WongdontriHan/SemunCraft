// Ships the combined units the game plays with — the Mage (bishop + rook), the Paladin (knight +
// knight) and the Guardian (knight + rook) — as markup the browser draws directly: pieces/units-art.js.
// The drawings are make.js's own, so these units on the board are the ones on the title screen; the
// <use> copies make.js shares between parts are written out in full, so no ids end up in the page.
// Run again after changing pieces/pieces.js or a theme set:
//   node pieces/combined/make-game-units.js
const fs=require('fs'),path=require('path');
const {unitMarkup,BOX}=require('./make.js');
const GAME_UNITS={mage:'Mage',paladin:'Paladin',guardian:'Guardian'};
const THEMES=['forest','jungle','desert','ocean'];

function inline(markup){
  const defs={};
  const body=markup.replace(/<defs>([\s\S]*?)<\/defs>/,(m,inner)=>{
    // each part is '<g id="…">…</g>', one after another, and a part never holds an id of its own
    inner.replace(/<g id="([^"]+)">([\s\S]*?)<\/g>(?=<g id="|$)/g,(mm,id,content)=>{defs[id]=content;return '';});
    return '';
  });
  return body.replace(/<use href="#([^"]+)" transform="([^"]+)"\/>/g,(m,id,tf)=>{
    if(!(id in defs))throw new Error('no part '+id);
    return '<g transform="'+tf+'">'+defs[id]+'</g>';
  });
}

// make.js draws in a 120-unit square where a normal piece's 100-unit box sits at TY..TY+100*scale;
// cropping to that box draws a unit at exactly the size of a normal piece
const ty=(120-100*BOX.scale)/2,side=100*BOX.scale;
const art={};
for(const[type,name]of Object.entries(GAME_UNITS)){
  art[type]={};
  for(const theme of THEMES)art[type][theme]={w:inline(unitMarkup(name,'w',theme)),b:inline(unitMarkup(name,'b',theme))};
}
const out='// Generated by pieces/combined/make-game-units.js from the drawings in pieces/combined/make.js:\n'
  +'// run that again after changing pieces/pieces.js or a theme set. pieceSVG draws these.\n'
  +'const UNIT_VIEWBOX='+JSON.stringify(ty+' '+ty+' '+side+' '+side)+';\n'
  +'const UNIT_ART='+JSON.stringify(art)+';\n';
fs.writeFileSync(path.join(__dirname,'..','units-art.js'),out);
console.log('pieces/units-art.js',out.length,'chars');
